import assert from 'node:assert/strict';
import { build } from 'esbuild';
const compiled = await build({stdin: {contents: `export { FlightAnimator } from './src/flight/FlightAnimator'; export { CameraController } from './src/map/CameraController'; export { AircraftController } from './src/map/AircraftController'; export { DEMO_ROUTES } from './src/data/demoRoutes';`, resolveDir: process.cwd()}, bundle: true, write: false, format: 'esm', platform: 'node'});
const { FlightAnimator, CameraController, AircraftController, DEMO_ROUTES } = await import('data:text/javascript;base64,' + Buffer.from(compiled.outputFiles[0].text).toString('base64'));
let frame;
globalThis.requestAnimationFrame = callback => { frame = callback; return 1; };
globalThis.cancelAnimationFrame = () => { frame = undefined; };
let latest;
const animator = new FlightAnimator(t => { latest = t; });
const advance = () => frame(animator.lastRafTimestamp + 40);
assert.equal(animator.getSpeed(), 1);
for (const route of DEMO_ROUTES) {
  animator.setRoute(route);
  animator.playForward(); advance();
  const departureStep = animator.getProgress();
  animator.seek(.5); advance();
  assert.ok(animator.getProgress() - .5 > departureStep * 3);
  animator.playReverse(); const before = animator.getProgress(); advance();
  assert.ok(animator.getProgress() < before);
  animator.seek(.000001); advance();
  assert.equal(latest.progress, 0); assert.equal(animator.getIsPlaying(), false);
  animator.seek(.999999); animator.playForward(); advance();
  assert.equal(latest.progress, 1); assert.equal(animator.getIsPlaying(), false);
  animator.playReverse(); advance(); assert.ok(animator.getProgress() < 1);
  animator.setRoute(route); assert.equal(frame, undefined);
}
animator.setSpeed(17.5); assert.equal(animator.getSpeed(), 17.5);
animator.setSpeed(99); assert.equal(animator.getSpeed(), 60);
animator.setSpeed(0); assert.equal(animator.getSpeed(), 1);
const map = { stopCameraAnimation() {}, appendChild(model) { this.model = model; } };
const camera = new CameraController(map);
const telemetry = {...latest, lat: 35, lng: 140, altitude: 1000, heading: 0, pitch: 0, roll: 0};
camera.setMode('COCKPIT'); camera.update(telemetry);
const eyeForward = (map.center.lat - telemetry.lat) * 111320 - map.range * Math.sin(map.tilt * Math.PI / 180);
assert.ok(Math.abs(eyeForward - 40) < .001);
telemetry.lat += .1; camera.update(telemetry);
assert.ok(Math.abs((map.center.lat - telemetry.lat) * 111320 - 60) < .001, 'cockpit must not lag behind aircraft');
camera.setMode('CLOSE'); camera.update(telemetry); assert.equal(map.range, 65);
const aircraft = new AircraftController({ Model3DElement: class { constructor(options) { Object.assign(this, options); } }, AltitudeMode: {ABSOLUTE: 'ABSOLUTE'} }, map);
aircraft.update(telemetry);
assert.equal(map.model.orientation.heading, 270); assert.equal(map.model.orientation.tilt, 270);
assert.equal(aircraft.getHeadingDelta(), 0); assert.equal(aircraft.getTiltDelta(), 0);
const orientation = { ...map.model.orientation };
for (const mode of ['CLOSE', 'FOLLOW', 'COCKPIT', 'OVERVIEW', 'FREE']) {
  camera.setMode(mode);
  camera.setHeadingOffset(0);
  camera.update(telemetry);
  const heading = map.heading;
  camera.setHeadingOffset(90);
  camera.setTilt(45);
  camera.update(telemetry);
  assert.equal(Math.round(map.heading), (Math.round(heading) + 90) % 360, mode);
  assert.equal(map.tilt, 45, mode);
  camera.update(telemetry);
  assert.equal(map.tilt, 45, 'tilt persists across tracking ticks');
  aircraft.update(telemetry);
  assert.deepEqual(map.model.orientation, orientation, 'camera controls preserve aircraft orientation');
}
camera.setMode('CLOSE'); camera.setTilt(-1); camera.update(telemetry);
assert.equal(map.tilt, 78, 'AUTO restores camera preset');
console.log('Passed: all 4 routes, forward/reverse endpoints, departure pacing, speed bounds, cockpit tracking, close camera, baseline orientation.');
